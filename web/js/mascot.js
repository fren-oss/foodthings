// ----------------------------------------------------------------------------
// Helpers
// ----------------------------------------------------------------------------

export function poseSrc(pose) {
  const file = (POSES[pose] || POSES.santai).file;
  return `${ASSET_BASE}${file.endsWith('.webp') ? file : `${file}.png`}`;
}

export function poseAlt(pose) {
  return (POSES[pose] || POSES.santai).alt;
}

export function poseAnim(pose) {
  return (POSES[pose] || POSES.santai).anim;
}

// Build a <img> string for a pose. Sizing/positioning stays with the caller
// through `className`; this only centralizes src, alt, accessibility and the
// animation contract (`data-limo` / `data-anim`).
export function mascotImg(pose, opts = {}) {
  const key = POSES[pose] ? pose : 'santai';
  const {
    className = '',
    anim = poseAnim(key),
    interactive = false,
    decorative = true,
    id = '',
    size = null,
    lazy = true,
    alt,
    bobDuration = null,
  } = opts;

  const animatedWave = anim === 'wave' && willPlayWave();
  const src = animatedWave ? WAVE_SRC : poseSrc(key);
  const dims = size ? ` width="${size}" height="${size}"` : '';
  const cls = ['limo-img', className].filter(Boolean).join(' ');
  const altText = alt !== undefined ? alt : (decorative ? '' : poseAlt(key));
  const hidden = decorative ? ' aria-hidden="true"' : '';

  return [
    `<img src="${src}"${dims}`,
    ` class="${cls}"`,
    ` data-limo="${key}" data-anim="${anim}"`,
    animatedWave ? ' data-wave-play="1"' : '',
    id ? ` id="${id}"` : '',
    interactive ? ' data-interactive="true"' : '',
    bobDuration ? ` data-bob-duration="${bobDuration}"` : '',
    ` alt="${altText}"${hidden}`,
    lazy && !animatedWave ? ' loading="lazy" decoding="async"' : '',
    ' />',
  ].join('');
}

// Optional standalone component (mascot + caption). Views normally embed
// `mascotImg` directly so keep their own layout; this remains for reuse.
export function renderMascot(pose, text = '', className = '') {
  const caption = text ? `<p class="limo-caption font-label-md text-label-md text-on-surface mt-2 text-center">${text}</p>` : '';
  return `<div class="limo-wrap flex flex-col items-center ${className}">${mascotImg(pose, { className: 'limo-md' })}${caption}</div>`;
}

// ----------------------------------------------------------------------------
// Runtime: plays the named animations, enforcing the docs/DESIGN.md rules
// (wave on each open, bounded bob, loops only for think, etc.)
// ----------------------------------------------------------------------------

const DURATIONS = { wave: 1600, hop: 650, shake: 550 };
const BOB_MAX_MS = 10000; // bob rests after ~10s (docs/DESIGN.md -> Motion)

const mqReduce = (typeof window !== 'undefined' && window.matchMedia)
  ? window.matchMedia('(prefers-reduced-motion: reduce)')
  : null;

function prefersReduced() {
  return !!(mqReduce && mqReduce.matches);
}

// Whether the animated wave should start on this render: every time the
// screen that mounts this pose is opened, but never under reduced-motion.
function willPlayWave() {
  return !prefersReduced();
}

function playOnce(img, cls, ms) {
  img.classList.remove(cls);
  // force a reflow so the keyframes restart if the class was already present
  void img.offsetWidth;
  img.classList.add(cls);
  if (ms) setTimeout(() => img.classList.remove(cls), ms);
}

function mountAnim(img) {
  const anim = img.dataset.anim || 'none';

  // Static poses get a gentle opacity-only entrance so a pose change reads
  // as a soft cross-fade instead of an abrupt swap.
  if (anim === 'none') {
    playOnce(img, 'limo-enter', 220);
    return;
  }

  if (anim === 'wave') {
    if (img.dataset.wavePlay === '1') {
      // The animated WebP is already on screen; swap to the static rest frame
      // when it finishes so the wave plays exactly once per open and never loops.
      setTimeout(() => {
        if (!document.contains(img)) return;
        img.src = poseSrc(img.dataset.limo);
        img.removeAttribute('data-wave-play');
      }, WAVE_MS);
    } else {
      playOnce(img, 'limo-wave', DURATIONS.wave);
    }
    return;
  }

  if (anim === 'think') { img.classList.add('limo-think'); return; }
  if (anim === 'hop')   { playOnce(img, 'limo-hop', DURATIONS.hop); return; }
  if (anim === 'shake') { playOnce(img, 'limo-shake', DURATIONS.shake); return; }

  if (anim === 'bob') {
    img.classList.add('limo-bob');
    const dur = parseInt(img.dataset.bobDuration || String(BOB_MAX_MS), 10);
    if (dur > 0) setTimeout(() => img.classList.remove('limo-bob'), dur);
  }
}

// Playful tap: hop once, then resume the pose's idle loop if it had one.
function tapLimo(img) {
  if (prefersReduced()) return;
  ['limo-think', 'limo-bob', 'limo-wave'].forEach((c) => img.classList.remove(c));
  playOnce(img, 'limo-hop', DURATIONS.hop);
  const after = img.dataset.anim;
  if (after === 'think' || after === 'bob') {
    setTimeout(() => {
      if (document.contains(img)) img.classList.add(`limo-${after}`);
    }, DURATIONS.hop + 40);
  }
}

// Cross-fade to another pose on an already-mounted image (200ms per DESIGN).
export function swapMascot(imgEl, pose) {
  const p = POSES[pose];
  if (!imgEl || !p || imgEl.dataset.limo === pose) return imgEl;

  imgEl.classList.add('limo-fading');
  ['limo-think', 'limo-bob', 'limo-wave', 'limo-hop', 'limo-shake'].forEach((c) => imgEl.classList.remove(c));

  setTimeout(() => {
    imgEl.src = poseSrc(pose);
    imgEl.dataset.limo = pose;
    imgEl.dataset.anim = p.anim;
    if (imgEl.getAttribute('aria-hidden') !== 'true') imgEl.alt = p.alt;
    imgEl.classList.remove('limo-fading');
    if (!prefersReduced()) mountAnim(imgEl);
  }, 120);

  return imgEl;
}

// Scan a rendered subtree and activate every `img[data-limo]` exactly once.
export function initMascotAnims(root = document) {
  if (!root || !root.querySelectorAll) return;
  const reduce = prefersReduced();

  root.querySelectorAll('img[data-limo]').forEach((img) => {
    if (img.dataset.limoReady === '1') return;
    img.dataset.limoReady = '1';
    img.classList.add('limo-img');

    if (reduce) img.classList.add('limo-rest');
    else mountAnim(img);

    if (img.dataset.interactive === 'true') {
      img.classList.add('limo-interactive');
      img.addEventListener('click', () => tapLimo(img));
    }
  });
}
